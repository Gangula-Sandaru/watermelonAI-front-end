export const useTranslation = () => {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('language_preference') || 'en';
  });

  useEffect(() => {
    const handleLanguageChange = (e: any) => {
      setLang(e.detail || 'en');
    };
    window.addEventListener('watermelon-language-change' as any, handleLanguageChange);
    return () => {
      window.removeEventListener('watermelon-language-change' as any, handleLanguageChange);
    };
  }, []);

  const t = (key: keyof typeof translations['en']) => {
    const translationMap = translations[lang] || translations['en'];
    return translationMap[key] || translations['en'][key] || String(key);
  };

  return { t, currentLanguage: lang };
};
